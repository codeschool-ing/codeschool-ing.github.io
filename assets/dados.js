/* ==========================================================================
   codeschool.ing — catálogo de cursos e trilhas

   Como manter: os cursos e as trilhas do site são montados a partir
   deste arquivo. Um curso pode aparecer em quantas trilhas for
   necessário — basta citar o `id` dele na sequência da trilha, e o
   site calcula sozinho o selo "em N trilhas".

   Os cursos marcados como BASE foram desenhados para servir também às
   próximas trilhas (Back-end, Dados, DevOps...), sem duplicação.

   VÍDEO DE APRESENTAÇÃO: cada curso pode ter um campo `video` com o id do
   vídeo no YouTube — só o id, não a URL inteira:

     { id: 'git', video: 'dQw4w9WgXcQ', ... }

   O modal mostra a capa do vídeo e só carrega o player do YouTube depois
   que o aluno clica: ninguém paga o custo (nem os cookies) de um vídeo que
   não vai assistir. Curso sem `video` mostra o quadro reservado com "vídeo
   em breve" — o espaço já fica guardado, então publicar o vídeo depois não
   reorganiza nada na tela.

   Cada curso tem dois níveis de conteúdo:
     `ementa`  — 5 a 7 linhas, leitura comercial: o que o aluno leva.
     `topicos` — lista completa e técnica, exibida no modal dentro de um
                 bloco recolhido ("conteúdo detalhado"). É opcional: curso
                 sem `topicos` simplesmente não mostra o bloco.

   Idioma dos nomes: conceito em português ("Infraestrutura como Código"),
   nome próprio de tecnologia intacto ("JavaScript", "Node.js", "GitOps").
   Nas trilhas, o nome é em português e o cargo em inglês fica no campo
   `saida`, que é como o mercado anuncia a vaga.

   ETAPAS COM BIFURCAÇÃO: um item de `cursos` normalmente é o id de um
   curso (string). Quando a trilha precisa deixar a decisão para o aluno,
   o item vira um objeto:

     {
       escolha: 'a linguagem do servidor',
       nota: 'texto explicando a decisão',   // opcional
       opcoes: [
         { nome: 'Java', cursos: ['java-back'] },
         { nome: 'Python', cursos: ['python', 'python-back'] },
       ],
     }

   Cada opção pode ter um ou vários cursos, e a carga horária da trilha
   muda conforme o caminho — o site recalcula e mostra a faixa. A primeira
   opção é a sugerida por padrão.
   ========================================================================== */

